def main():
    ok, ng = [], []
    for name, la, lo in PROBES:
        try:
            g = mapillary.images_around(la, lo, limit=3)
            (ok if g else ng).append(name)
            print(f"{'○' if g else '×'} {name}", flush=True)
        except Exception as e:
            ng.append(name)
            print(f"! {name} {type(e).__name__}", flush=True)
    print(f"\n写真あり {len(ok)} / なし {len(ng)}")
    if ng:
        print("なし:", " ".join(ng))
    Path("data/coverage.json").write_text(
        json.dumps({"ok": ok, "ng": ng}, ensure_ascii=False, indent=1), encoding="utf-8")


if __name__ == "__main__":
    main()
